        [Test]
        public void CustomRowClassTemplateReplacesDefault()
        {
            const string template =
                "{{Header}}\n" +
                "// custom {{Unknown}}\n" +
                "namespace {{Namespace}}\n" +
                "{\n" +
                "    public class {{ClassName}}Row\n" +
                "    {\n" +
                "{{Fields}}\n" +
                "    }\n" +
                "}\n";
            var options = new CodeGenOptions(Namespace, template);

            var text = CodeGenerator.GenerateRowClass("Units", Columns("id", "hp:int"), options);

            Assert.That(text, Is.EqualTo(
                CodeGenerator.Header + "\n" +
                "// custom {{Unknown}}\n" +
                "namespace Game.Data\n" +
                "{\n" +
                "    public class UnitsRow\n" +
                "    {\n" +
                "        public string id;\n" +
                "        public int hp;\n" +
                "    }\n" +
                "}\n"));
        }

