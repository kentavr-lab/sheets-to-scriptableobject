        private static SheetParseResult Sheet(string name, params string[][] rows)
        {
            var result = SheetParser.Parse(name, rows);
            Assert.That(result.IsValid, Is.True, string.Join("; ", result.Errors));
            return result;
        }

        [Test]
        public void CollectEnumMembersKeepsOrderAndRemovesDuplicates()
        {
            var units = Sheet("Units",
                new[] { "id", "rarity:enum<Rarity>", "kinds:enum<Kind>[]", "hp:int" },
                new[] { "knight", "Rare", "Melee|Heavy", "10" },
                new[] { "archer", "Common", "Ranged|Melee", "5" },
                new[] { "mage", "Rare", "", "3" });
            var weapons = Sheet("Weapons",
                new[] { "id", "kind:enum<Kind>", "rarity:enum<Rarity>[]" },
                new[] { "sword", "Melee", "Epic|Common" },
                new[] { "bow", "Thrown", "" });

            var result = CodeGenerator.CollectEnumMembers(new[] { units, weapons });

            Assert.That(result.IsValid, Is.True, string.Join("; ", result.Errors));
            Assert.That(result.EnumNames, Is.EqualTo(new[] { "Rarity", "Kind" }));
            Assert.That(result.Members["Rarity"], Is.EqualTo(new[] { "Rare", "Common", "Epic" }));
            Assert.That(result.Members["Kind"], Is.EqualTo(new[] { "Melee", "Heavy", "Ranged", "Thrown" }));
        }

        [Test]
