        private static ColumnDefinition[] Columns(params string[] cells)
        {
            var result = HeaderParser.Parse(cells);
            Assert.That(result.IsValid, Is.True, string.Join("; ", result.Errors));
            return result.Columns.ToArray();
        }

        private static CodeGenOptions Options(string ns = Namespace) => new CodeGenOptions(ns);

