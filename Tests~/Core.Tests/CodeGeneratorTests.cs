        [Test]
        public void CollectEnumMembersReportsInvalidValueWithAddress()
        {
            var sheet = Sheet("Units",
                new[] { "id", "name", "rarity:enum<Rarity>", "kinds:enum<Kind>[]" },
                new[] { "knight", "Knight", "Rare", "Melee" },
                new[] { "archer", "Archer", "Common", "Melee" },
                new[] { "mage", "Mage", "Rare", "class" },
                new[] { "dragon", "Dragon", "Epic Item", "Melee" });

            var result = CodeGenerator.CollectEnumMembers(new[] { sheet });

            Assert.That(result.IsValid, Is.False);
            Assert.That(result.Errors.Select(e => e.Address), Is.EqualTo(new[] { "Units!D4", "Units!C5" }));
            Assert.That(result.Errors[1].Message, Does.Contain("Epic Item"));
            Assert.That(result.Errors[1].CellCode, Is.EqualTo(CellErrorCode.InvalidEnumValue));
            Assert.That(result.Members["Rarity"], Is.EqualTo(new[] { "Rare", "Common" }));
        }

