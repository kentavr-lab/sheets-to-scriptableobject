        [Test]
        public void OutputStartsWithAutoGeneratedHeader()
        {
            var rowClass = CodeGenerator.GenerateRowClass("Units", Columns(UnitsHeader), Options());
            var enumText = CodeGenerator.GenerateEnum("Rarity", RarityMembers, Options());

            Assert.That(rowClass, Does.StartWith(CodeGenerator.Header + "\n"));
            Assert.That(enumText, Does.StartWith(CodeGenerator.Header + "\n"));
            Assert.That(CodeGenerator.Header, Does.StartWith("// <auto-generated>"));
            Assert.That(CodeGenerator.Header, Does.Contain("Do not edit manually"));
        }

        [Test]
        public void OutputUsesOnlyLineFeeds()
        {
            var rowClass = CodeGenerator.GenerateRowClass("Units", Columns(UnitsHeader), Options());
            var enumText = CodeGenerator.GenerateEnum("Rarity", RarityMembers, Options());

            foreach (var text in new[] { rowClass, enumText })
            {
                Assert.That(text, Does.Not.Contain("\r"));
                Assert.That(text, Does.Not.Contain("\t"));
                Assert.That(text.Split('\n').Where(line => line.EndsWith(" ")), Is.Empty);
            }
        }

